fun baseKey(token: String): String {
    val n = java.text.Normalizer.normalize(token, java.text.Normalizer.Form.NFD)
    val sb = StringBuilder()
    for (c in n) {
        if (Character.getType(c) != Character.NON_SPACING_MARK.toInt()) sb.append(c)
    }
    return sb.toString().lowercase(java.util.Locale.ROOT)
}

